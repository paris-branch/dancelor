let view context id =
  Main_page.madge_call_or_404 (Book Get_view) id @@ fun book ->
  Page.make'
    ~parent_title: "Book"
    ~before_title: [
      Components.Context_links.make_and_render_new
        ?context
        ~this_page: (Endpoints.Page.href_book id)
        (Any_id.Book id);
    ]
    ~title: (lwt book.name)
    ~subtitles: [span (Formatters_new.Book.date_and_editors book)]
    ~share_new: (Book id)
    ~actions: [
      lwt [
        Button.make
          ~label: "Download PDF"
          ~icon: (Other File_pdf)
          ~onclick: (fun _ -> ignore <$> Book_download_dialog.create_and_open book)
          ~dropdown: true
          ();
      ];
      (
        (* FIXME: check permission to know whether to show this *)
        (* match%lwt Permission.can_update_private book with *)
        (* | None -> lwt_nil *)
        (* | Some _ -> *)
        lwt [
          Button.make_a
            ~label: "Edit"
            ~icon: (Action Edit)
            ~href: (S.const @@ Endpoints.Page.(href @@ Book Edit) id)
            ~dropdown: true
            ();
        ]
      );
      (
        (* FIXME: check permission to know whether to show this *)
        (* match%lwt Permission.can_delete_private book with *)
        (* | None -> lwt_nil *)
        (* | Some _ -> *)
        lwt [
          Action.delete
            ~model: "book"
            ~onclick: (fun () -> Madge_client.call Endpoints.Api.(route @@ Book Delete) id)
            ();
        ]
      );
      (lwt @@ Option.map_to_list (Action.scddb Publication) book.scddb_id);
    ]
    [
      div (
        match book.warnings with
        | [] -> []
        | warnings -> [div ~a: [a_class ["alert"; "alert-warning"]] [ul ~a: [a_class ["mb-0"]] (display_warnings warnings)]]
      );
      div [
        h3 [txt "Contents"];
        table_contents ~this_id: id book.content;
      ];
    ]
